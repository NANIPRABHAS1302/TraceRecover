def main() -> None:
    specs = _build_holdout_specs()
    prov_suite = _build_provenance_audit_suite()
    contra_suite = _build_contradiction_audit_suite()

    # 1. Verify zero overlap with all historical benchmarks
    historical_files = [
        PROJECT_ROOT / "eval" / "tasks.json",
        DATA_DIR / "phase6_unseen_50.json",
        DATA_DIR / "phase7_unseen_60.json",
        DATA_DIR / "phase7_1_unseen.json",
        DATA_DIR / "phase7_2_live_unseen.json",
    ]
    hist_norm: set[str] = set()
    for hf in historical_files:
        if not hf.exists():
            continue
        raw = json.loads(hf.read_text(encoding="utf-8"))
        items = raw if isinstance(raw, list) else raw.get("tasks", [])
        for it in items:
            q = it.get("question") or it.get("query") or ""
            if q:
                hist_norm.add(_norm_q(q))

    seen_ids: set[str] = set()
    seen_q: set[str] = set()
    for s in specs:
        tid = s["task_id"]
        nq = _norm_q(s["question"])
        assert tid not in seen_ids, f"Duplicate task_id: {tid}"
        assert nq not in seen_q, f"Duplicate question: {tid}"
        assert nq not in hist_norm, f"Historical overlap detected on {tid}: {s['question']}"
        seen_ids.add(tid)
        seen_q.add(nq)

    # 2. Verify domain & category quotas
    domains = sorted({s["domain"] for s in specs})
    assert len(specs) >= 80, f"Need >=80 tasks, got {len(specs)}"
    assert len(domains) >= 16, f"Need >=16 domains, got {len(domains)}"

    cat_counts: dict[str, int] = {}
    for s in specs:
        for c in s["categories"]:
            cat_counts[c] = cat_counts.get(c, 0) + 1

    # Add dedicated Task D provenance & Task E contradiction counts into audit coverage summary
    quotas = {
        "general_factual_research": 12,
        "technical_documentation": 12,
        "academic_research": 12,
        "multi_step_research": 10,
        "multi_source_research": 10,
        "study_provenance_attribution": 12,
        "context_aware_contradiction": 12,
        "insufficient_evidence_abstention": 8,
        "numerical_temporal_verification": 8,
    }
    # Verify Task A categories across end-to-end holdout (and note overlap with Task D/E dedicated suites)
    e2e_provenance = cat_counts.get("study_provenance_attribution", 0)
    e2e_contra = cat_counts.get("context_aware_contradiction", 0)
    # Also ensure end-to-end tasks themselves hit >=12 provenance and >=12 contradiction? Let's check!
    print("E2E Category counts:", json.dumps(cat_counts, indent=2))
    print(f"Total E2E tasks: {len(specs)}, Domains: {len(domains)}, Prov suite: {len(prov_suite)}, Contra suite: {len(contra_suite)}")

    # Check if any E2E category is below quota
    shortfalls = {k: (cat_counts.get(k, 0), v) for k, v in quotas.items() if cat_counts.get(k, 0) < v}
    if shortfalls:
        raise AssertionError(f"Category quota shortfalls in E2E holdout: {shortfalls}")

    # 3. Write strictly separated public holdout file (NO expected answers/labels!)
    public_tasks = []
    gold_tasks = []
    for s in specs:
        pub = {
            "task_id": s["task_id"],
            "domain": s["domain"],
            "categories": s["categories"],
            "question": s["question"],
            "fixture_type": s["fixture_type"],
            "mock_mode": s["mock_mode"],
            "live_probe": bool(s.get("live_probe", False)),
            "fault_injection": bool(s.get("fault_injection", False)),
        }
        if s.get("history"):
            pub["history"] = s["history"]
        public_tasks.append(pub)

        gold = {
            "task_id": s["task_id"],
            "domain": s["domain"],
            "categories": s["categories"],
            "fixture_type": s["fixture_type"],
            "expected_decision": s["expected_decision"],
            "expected_answer_criteria": {
                "required_substrings": s["required_substrings"],
                "required_supporting_claims": s["required_supporting_claims"],
            },
            "expected_evidence_sources": s["expected_evidence_sources"],
            "expected_source_urls": s["expected_source_urls"],
            "expected_citation_relationships": s["expected_citation_relationships"],
            "expected_contradiction_label": s["expected_contradiction_label"],
            "expected_contradiction_class": s["expected_contradiction_class"],
            "expected_abstention_behavior": s["expected_abstention_behavior"],
            "expected_tool": s["expected_tool"],
            "evaluation_rationale": s["evaluation_rationale"],
        }
        gold_tasks.append(gold)

    holdout_path = DATA_DIR / "phase7_4_independent_holdout.json"
    gold_path = DATA_DIR / "phase7_4_holdout_gold.json"
    manifest_path = DATA_DIR / "phase7_4_holdout_manifest.json"

    holdout_obj = {
        "dataset_name": "TraceRecover Phase 7.4 Independent Holdout Benchmark",
        "dataset_version": "1.0.0",
        "frozen": True,
        "contains_gold_labels": False,
        "separated_from_historical_benchmarks": True,
        "question_count": len(public_tasks),
        "domain_count": len(domains),
        "domains": domains,
        "category_counts": cat_counts,
        "tasks": public_tasks,
    }
    gold_obj = {
        "gold_name": "TraceRecover Phase 7.4 Protected Holdout Gold Labels",
        "dataset_version": "1.0.0",
        "frozen": True,
        "must_not_be_exposed_to_agent": True,
        "e2e_task_count": len(gold_tasks),
        "provenance_audit_count": len(prov_suite),
        "contradiction_audit_count": len(contra_suite),
        "tasks": gold_tasks,
        "provenance_audit_cases": prov_suite,
        "contradiction_audit_cases": contra_suite,
    }

    holdout_path.write_text(json.dumps(holdout_obj, indent=2), encoding="utf-8")
    gold_path.write_text(json.dumps(gold_obj, indent=2), encoding="utf-8")

    manifest = {
        "dataset_version": "1.0.0",
        "frozen_at_utc": datetime.now(timezone.utc).isoformat(),
        "files": {
            "phase7_4_independent_holdout.json": {
                "sha256": _sha256_file(holdout_path),
                "bytes": holdout_path.stat().st_size,
                "question_count": len(public_tasks),
                "domain_count": len(domains),
            },
            "phase7_4_holdout_gold.json": {
                "sha256": _sha256_file(gold_path),
                "bytes": gold_path.stat().st_size,
                "e2e_task_count": len(gold_tasks),
                "provenance_audit_count": len(prov_suite),
                "contradiction_audit_count": len(contra_suite),
            },
        },
    }
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print("FROZEN MANIFEST:")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
